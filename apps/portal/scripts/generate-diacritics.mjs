// Writes core/diacritics.py: the code points JavaScript's \p{Diacritic}
// matches, as inclusive ranges. The site's slugify (apps/web/lib/animal-path.ts)
// drops that property before it turns the rest into dashes, and the portal's
// Python copy of the rule (core/site_links.py) has to drop the same set. Python
// has no way to ask for the property, so it is read off node here, the engine
// that builds the site, and pasted in as data.
//
//   node apps/portal/scripts/generate-diacritics.mjs           writes the file
//   node apps/portal/scripts/generate-diacritics.mjs --check   fails if it moved
//
// The property is not frozen: node carries its own ICU, .node-version pins only
// the major, and an ICU upgrade inside a major line would move the site's
// answers while the committed table stayed put. So --check runs in `pnpm
// lint:shell`, and a node that disagrees with the table fails the pull request
// that introduced it rather than silently pointing the admin's links at pages
// that do not exist.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const TARGET = join(dirname(fileURLToPath(import.meta.url)), "..", "core", "diacritics.py");

/** Every code point this node matches, collapsed into inclusive ranges. */
function currentRanges() {
  const ranges = [];
  for (let point = 0; point <= 0x10ffff; point += 1) {
    if (point >= 0xd800 && point <= 0xdfff) continue;
    if (!/\p{Diacritic}/u.test(String.fromCodePoint(point))) continue;
    const last = ranges[ranges.length - 1];
    if (last && point === last[1] + 1) last[1] = point;
    else ranges.push([point, point]);
  }
  return ranges;
}

/** The ranges the committed module states, read back out of its own table. */
function committedRanges() {
  const source = readFileSync(TARGET, "utf8");
  return [...source.matchAll(/^ {4}\((0x[0-9A-F]+), (0x[0-9A-F]+)\),$/gm)].map(
    ([, low, high]) => [Number(low), Number(high)],
  );
}

const hex = (point) => `0x${point.toString(16).toUpperCase().padStart(4, "0")}`;

function render(ranges) {
  const lines = ranges.map(([low, high]) => `    (${hex(low)}, ${hex(high)}),`);
  return `r"""The code points JavaScript's \\p{Diacritic} matches, as inclusive ranges.

Generated by scripts/generate-diacritics.mjs, not written by hand. This is
the set the site's slugify drops before it turns the rest into dashes
(apps/web/lib/animal-path.ts), read off the engine that builds the site.
Node ${process.version}, ICU ${process.versions.icu}, Unicode ${process.versions.unicode}.
"""

RANGES: tuple[tuple[int, int], ...] = (
${lines.join("\n")}
)


# The ranges are what stays readable in a diff; the lookup wants the points
# themselves. slugify asks about every character of every name, town and
# shelter id it is given, which over one page of the admin is thousands of
# questions, and walking the ranges for each of them measured eight times
# slower than the rest of the page put together.
POINTS: frozenset[int] = frozenset(
    point for low, high in RANGES for point in range(low, high + 1)
)


def is_diacritic(letter: str) -> bool:
    """Whether the site's slugify drops this character before dashing."""
    return ord(letter) in POINTS
`;
}

const ranges = currentRanges();

if (process.argv.includes("--check")) {
  // Only the table is compared. The version line above it is provenance, and
  // a node upgrade that leaves the property alone must not fail anything.
  const committed = committedRanges();
  const shape = (rows) => rows.map(([low, high]) => `${hex(low)}-${hex(high)}`);
  const now = shape(ranges);
  const then = shape(committed);
  const moved = now.filter((row) => !then.includes(row));
  const dropped = then.filter((row) => !now.includes(row));
  if (moved.length || dropped.length) {
    console.error(
      [
        `diacritics: node ${process.version} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode})`,
        `disagrees with apps/portal/core/diacritics.py.`,
        moved.length ? `  this node adds: ${moved.slice(0, 8).join(", ")}` : "",
        dropped.length ? `  this node drops: ${dropped.slice(0, 8).join(", ")}` : "",
        `Regenerate with: node apps/portal/scripts/generate-diacritics.mjs`,
        `The site's URLs move with it, so re-run the portal tests after.`,
      ]
        .filter(Boolean)
        .join("\n"),
    );
    process.exit(1);
  }
  console.log(`diacritics: OK (${committed.length} ranges)`);
} else {
  writeFileSync(TARGET, render(ranges));
  console.log(`wrote ${TARGET}: ${ranges.length} ranges`);
}
