// Writes core/diacritics.py: the code points JavaScript's \p{Diacritic}
// matches, as inclusive ranges. The site's slugify (apps/web/lib/animal-path.ts)
// drops that property before it turns the rest into dashes, and the portal's
// Python copy of the rule (core/site_links.py) has to drop the same set. Python
// has no way to ask for the property, so it is read off node here, the engine
// that builds the site, and pasted in as data.
//
//   node apps/portal/scripts/generate-diacritics.mjs
//
// Run it again when node's Unicode tables move and commit the result.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ranges = [];
for (let point = 0; point <= 0x10ffff; point += 1) {
  if (point >= 0xd800 && point <= 0xdfff) continue;
  if (!/\p{Diacritic}/u.test(String.fromCodePoint(point))) continue;
  const last = ranges[ranges.length - 1];
  if (last && point === last[1] + 1) last[1] = point;
  else ranges.push([point, point]);
}

const hex = (point) => `0x${point.toString(16).toUpperCase().padStart(4, "0")}`;
const lines = ranges.map(([low, high]) => `    (${hex(low)}, ${hex(high)}),`);

const module = `r"""The code points JavaScript's \\p{Diacritic} matches, as inclusive ranges.

Generated by scripts/generate-diacritics.mjs, not written by hand. This is
the set the site's slugify drops before it turns the rest into dashes
(apps/web/lib/animal-path.ts), read off the engine that builds the site.
Node ${process.version}, ICU ${process.versions.icu}, Unicode ${process.versions.unicode}.
"""

RANGES: tuple[tuple[int, int], ...] = (
${lines.join("\n")}
)


def is_diacritic(letter: str) -> bool:
    """Whether the site's slugify drops this character before dashing."""
    point = ord(letter)
    # The table is small and the strings are short; a scan is enough.
    return any(low <= point <= high for low, high in RANGES)
`;

const target = join(dirname(fileURLToPath(import.meta.url)), "..", "core", "diacritics.py");
writeFileSync(target, module);
console.log(`wrote ${target}: ${ranges.length} ranges`);
