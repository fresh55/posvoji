import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const output = mkdtempSync(join(tmpdir(), "operation-types-"));
const names = ["artifact-lock", "generation-receipt"];
try {
  const run = spawnSync(process.execPath, [
    "apps/ingest/node_modules/typescript/bin/tsc", "--ignoreConfig", "--allowJs",
    "--declaration", "--emitDeclarationOnly", "--checkJs", "--skipLibCheck",
    "--strict", "false", "--strictNullChecks", "--noImplicitAny", "false", "--useUnknownInCatchVariables", "false",
    "--module", "NodeNext", "--target", "ES2022", "--types", "node",
    "--typeRoots", "apps/ingest/node_modules/@types", "--outDir", output,
    ...names.map((name) => `scripts/${name}.mjs`),
  ], { encoding: "utf8" });
  assert.equal(run.status, 0, `${run.error ?? ""}${run.stdout}${run.stderr}`);
  for (const name of names) {
    const generated = "// Generated by scripts/generate-operation-types.mjs. Do not edit.\n" + readFileSync(join(output, `${name}.d.mts`), "utf8").replaceAll("\r\n", "\n");
    const target = resolve(`scripts/${name}.d.mts`);
    if (process.argv.includes("--write")) writeFileSync(target, generated);
    else assert.equal(readFileSync(target, "utf8").replaceAll("\r\n", "\n"), generated, `Regenerate ${name} declarations with node scripts/generate-operation-types.mjs --write`);
  }
} finally { rmSync(output, { recursive: true, force: true }); }
console.log("generated operations declarations: OK");
